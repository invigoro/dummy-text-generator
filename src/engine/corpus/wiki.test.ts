import { describe, expect, it } from 'vitest';
import { cleanWikitext } from './wiki';

const page = [
  '{{Отексте',
  '|АВТОР=[[Михаил Юрьевич Лермонтов]] (1814-1841)',
  '|ДАТАПУБЛИКАЦИИ=1840<ref>Впервые&nbsp;— в {{Отечественные записки|год=1840}}.</ref>',
  '}}',
  '',
  '==== I. ТАМАНЬ ====',
  'Тамань&nbsp;— самый скверный городишко из всех приморских городов России.<ref>Note.</ref> Я там чуть-чуть',
  "не умер с голода, да ''еще'' в добавок меня хотели [[утопить|утопить]].",
  '',
  '* [[/Глава II|Глава II]]',
  '<poem>',
  'Уж как по вольной волюшке',
  '</poem>',
  '',
  ':«Кто идет?» — [[Казак]].',
  '{| class="wikitable"',
  '| a || b',
  '|}',
  '',
  '<center>Конец первой части.</center>',
  '',
  '== Примечания ==',
  '{{примечания}}',
  '',
  '[[Категория:Герой нашего времени|5]]',
  '[[fr:Un héros de notre temps/Taman]]',
].join('\n');

describe('cleanWikitext', () => {
  it('keeps the prose, a paragraph to a line', () => {
    expect(cleanWikitext(page)).toBe(
      'Тамань — самый скверный городишко из всех приморских городов России. Я там чуть-чуть не умер с голода, да еще в добавок меня хотели утопить.\n\n«Кто идет?» — Казак.\n',
    );
  });

  it('makes its fixes to each paragraph', () => {
    expect(cleanWikitext('Слово* и дело.', { fixes: [[/\*/g, '']] })).toBe('Слово и дело.\n');
  });
});
